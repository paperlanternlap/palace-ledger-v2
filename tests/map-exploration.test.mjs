import { isMissingMapSchema, locationPayload } from '../src/features/followers/locationPayload.js';

test('legacy location saves omit unsupported fields without treating connection errors as missing schema', () => {
  const values = { code: 'garden', zoneNumber: 1, name: 'Garden', shortName: 'Garden', category: 'Garden',
    tags: [], active: true, baseSuccessPercent: 60, sortOrder: 1, mapLabel: '14', selfCharacterIds: [1, 2] };
  const legacy = locationPayload(values, false);
  assert.equal('map_label' in legacy, false);
  assert.equal('self_character_ids' in legacy, false);
  assert.equal(legacy.code, 'garden');
  const upgraded = locationPayload(values, true);
  assert.equal(upgraded.map_label, '14');
  assert.deepEqual(upgraded.self_character_ids, [1, 2]);
  assert.equal(isMissingMapSchema({ code: 'PGRST204', message: "Could not find the 'map_label' column of 'exploration_locations' in the schema cache" }), true);
  assert.equal(isMissingMapSchema({ code: '42703', message: 'column exploration_locations.self_character_ids does not exist' }), true);
  assert.equal(isMissingMapSchema({ code: '42501', message: 'permission denied' }), false);
  assert.equal(isMissingMapSchema({ message: 'Failed to fetch' }), false);
});

test('map exploration: access, retries, quotas, staff resolution and inventory', async () => {
  const db = new PGlite();
  try {
    // Minimal baseline for the existing migrations; no production connection.
    await db.exec(`
      create role anon; create role authenticated;
      create schema auth;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql as 'select null::uuid';
      create function public.is_active_staff() returns boolean language sql as
        $$select coalesce(current_setting('test.staff', true), 'true') = 'true'$$;
      create table characters(id integer primary key, character_name text);
      create table follower_master(id bigint primary key, name text, owner_character_id integer,
        active boolean default true, status text default 'idle', updated_at timestamptz,
        weekly_mission_limit integer default 1, access_areas text[] default '{}', skill_type text, skill_value integer);
      create table follower_talents(id bigint generated always as identity primary key,
        follower_id bigint, talent_key text, modifier_percent integer);
      create table exploration_locations(id bigint generated by default as identity primary key,
        code text unique, zone_number integer unique, name text, short_name text, category text,
        summary text, tags text[] default '{}', active boolean default true, sort_order integer default 0);
      create table items(id bigint primary key, name text unique, active boolean default true,
        is_limited boolean default false, stock_quantity integer, updated_at timestamptz);
      create table character_inventory(id bigint generated always as identity primary key,
        character_id integer, item_name text, quantity integer, unique(character_id,item_name));
      create table inventory_transactions(item_id bigint, character_id integer, quantity_change integer,
        transaction_type text, note text, created_by uuid);
      create table character_history(character_id integer, action text not null, value text, type text);
    `);
    const migration = async (name) => db.exec(await readFile(new URL(`../supabase/migrations/${name}`, import.meta.url), 'utf8'));
    await migration('20260730_add_follower_explorations.sql');
    await db.exec('alter table follower_explorations add column location_id bigint, add column suitability_percent integer default 0');
    await migration('20260730235959_enforce_follower_location_access.sql');
    await migration('20260731000000_add_follower_mission_rolls.sql');
    // Reproduce the deployed OUT-parameter mismatch reported by the user.
    await db.exec(`drop function public.get_player_follower_explorations(integer);
      create function public.get_player_follower_explorations(p_character_id integer)
      returns table(id bigint, legacy_extra_column text) language sql as
      $$select 0::bigint, 'legacy'::text$$;`);
    await migration('20260929000000_map_exploration_v1.sql');
    await migration('20260929001000_seed_palace_map.sql');
    const scalar = async (sql) => (await db.query(sql)).rows[0].value;
    assert.equal(await scalar('select count(*)::int as value from exploration_locations'), 48);
    assert.equal(await scalar('select count(*)::int as value from exploration_locations where active'), 0);
    await db.exec(`
      insert into characters values(1,'Player'),(2,'Other');
      insert into items(id,name,stock_quantity,is_limited) values(1,'Ready item',10,true);
      update exploration_locations set active=true, self_character_ids='{1}' where code='medical_bureau';
      insert into follower_master(id,name,owner_character_id,access_areas) values(1,'Follower',1,'{medical_bureau}'),(2,'Other follower',2,'{medical_bureau}');
    `);
    const place = await scalar("select id as value from exploration_locations where code='medical_bureau'");
    const start = (request, char = 1, follower = 'null') => db.query(`select (public.start_map_exploration(${char},${place},'00000000-0000-4000-8000-${String(request).padStart(12, '0')}',${follower})).*`);
    await assert.rejects(start(1, 2), /access required/);
    await assert.rejects(start(2, 1, 2), /not available/);
    const first = (await start(3)).rows[0];
    assert.equal(first.success_chance_percent, 60);
    assert.equal((await start(3)).rows[0].id, first.id);
    await assert.rejects(start(3, 1, 1), /does not match/);
    await assert.rejects(start(4), /active exploration/);
    const map = (await db.query('select get_player_exploration_map(1) as map')).rows[0].map;
    assert.equal(map[0].can_explore_self, false);
    assert.equal('self_character_ids' in map[0], false);

    await db.exec("set test.staff='false'");
    await assert.rejects(db.query(`select roll_follower_exploration(${first.id})`), /Staff access/);
    await assert.rejects(db.query(`select resolve_follower_exploration(${first.id},'Done')`), /Staff access/);
    await db.exec("set test.staff='true'");
    await db.query(`select roll_follower_exploration(${first.id})`);
    await assert.rejects(db.query(`select roll_follower_exploration(${first.id})`), /already been rolled/);
    await db.exec(`update follower_explorations set resolution_outcome='failure' where id=${first.id}`);
    await assert.rejects(db.query(`select resolve_follower_exploration(${first.id},'Failed',null,1,1)`), /cannot grant/);
    assert.equal(await scalar('select count(*)::int as value from character_inventory'), 0);
    assert.equal(await scalar('select stock_quantity as value from items where id=1'), 10);
    await db.exec(`update follower_explorations set resolution_outcome='success' where id=${first.id}`);
    await assert.rejects(db.query(`select resolve_follower_exploration(${first.id},'Done',null,1,2)`), /at most one/);
    await db.query(`select resolve_follower_exploration(${first.id},'Done','Staff-only note',1,1)`);
    assert.equal(await scalar('select quantity as value from character_inventory where character_id=1'), 1);
    assert.equal(await scalar('select stock_quantity as value from items where id=1'), 9);
    await assert.rejects(db.query(`select resolve_follower_exploration(${first.id},'Again',null,1,1)`), /not found/);
    await assert.rejects(start(5), /round limit/);
    const history = (await db.query('select * from get_player_follower_explorations(1)')).rows;
    assert.equal(history[0].result_details, null);
    assert.equal(history[0].reward_item_name, 'Ready item');

    await db.exec('update exploration_settings set round_number=2');
    const second = (await start(6)).rows[0];
    await db.query(`select cancel_follower_exploration(${second.id},'Cancelled')`);
    assert.ok((await start(7)).rows[0].id);
    const followerMission = (await start(8,1,1)).rows[0];
    assert.equal(await scalar('select status as value from follower_master where id=1'), 'exploring');
    assert.equal((await start(8,1,1)).rows[0].id, followerMission.id);
    await assert.rejects(start(9,1,1), /already on a mission/);
    await db.query(`select roll_follower_exploration(${followerMission.id})`);
    await db.query(`select resolve_follower_exploration(${followerMission.id},'Done')`);
    await assert.rejects(start(10,1,1), /weekly mission limit/);
    await db.exec("update follower_master set active=false where id=1");
    await assert.rejects(start(11,1,1), /not available/);
    // Re-running the installer must preserve progress, stock, access and rounds.
    await migration('20260929000000_map_exploration_v1.sql');
    await migration('20260929001000_seed_palace_map.sql');
    assert.equal(await scalar('select round_number as value from exploration_settings'), 2);
    assert.equal(await scalar('select quantity as value from character_inventory where character_id=1'), 1);
    assert.equal(await scalar('select stock_quantity as value from items where id=1'), 9);
    assert.equal(await scalar('select count(*)::int as value from exploration_locations'), 48);
    assert.equal(await scalar("select has_function_privilege('anon','public.get_player_follower_explorations(integer)','EXECUTE') as value"), true);
    await migration('20260929002000_remove_exploration_quotas.sql');
    await db.exec("update follower_master set active=true where id=1");
    assert.ok((await start(20,1,1)).rows[0].id);
    await db.exec("update follower_explorations set status='cancelled' where follower_id is null and status='exploring'");
    const unlimited = (await start(21)).rows[0];
    await db.query(`select roll_follower_exploration(${unlimited.id})`);
    await db.query(`select resolve_follower_exploration(${unlimited.id},'Done')`);
    assert.ok((await start(22)).rows[0].id);
    await assert.rejects(start(23), /active exploration/);
    await migration('20260929002000_remove_exploration_quotas.sql');
    assert.equal(await scalar('select quantity as value from character_inventory where character_id=1'), 1);
    await migration('20260929004000_player_exploration_outcome.sql');
    const oldPendingId = await scalar("select id as value from follower_explorations where follower_id is null and status='exploring' limit 1");
    const drawn = (await db.query(`select (draw_player_exploration_result(1,${oldPendingId})).*`)).rows[0];
    assert.ok(['success', 'failure'].includes(drawn.resolution_outcome));
    assert.equal(drawn.roll_origin, 'player');
    assert.equal((await db.query(`select (draw_player_exploration_result(1,${oldPendingId})).*`)).rows[0].resolution_outcome, drawn.resolution_outcome);
    await assert.rejects(db.query(`select draw_player_exploration_result(2,${oldPendingId})`), /not found/);
    await assert.rejects(db.query(`select roll_follower_exploration(${oldPendingId})`), /drawn by the player/);
    await db.query(`select cancel_follower_exploration(${oldPendingId},'Cancelled')`);
    const oldFollowerPendingId = await scalar("select id as value from follower_explorations where follower_id=1 and status='exploring' limit 1");
    await db.query(`select cancel_follower_exploration(${oldFollowerPendingId},'Cancelled')`);
    await db.exec(`update exploration_locations set base_success_percent=50, tags='{herb}' where id=${place};
      insert into follower_talents(follower_id,talent_key,modifier_percent) values(1,'herb',40);`);
    const playerStarted = (await start(24,1,1)).rows[0];
    assert.equal(playerStarted.success_chance_percent, 70);
    assert.ok(['success', 'failure'].includes(playerStarted.resolution_outcome));
    assert.equal(playerStarted.resolution_roll, null);
    assert.equal((await start(24,1,1)).rows[0].resolution_outcome, playerStarted.resolution_outcome);
    const playerHistory = (await db.query('select * from get_player_follower_explorations(1)')).rows;
    assert.equal(playerHistory[0].resolution_outcome, playerStarted.resolution_outcome);
    assert.equal(playerHistory[0].result_details, null);
    if (playerStarted.resolution_outcome === 'success') {
      await db.query(`select resolve_follower_exploration(${playerStarted.id},'Staff summary',null,1,1)`);
      assert.equal(await scalar('select quantity as value from character_inventory where character_id=1'), 2);
    } else {
      await assert.rejects(db.query(`select resolve_follower_exploration(${playerStarted.id},'Failed',null,1,1)`), /cannot grant/);
      await db.query(`select resolve_follower_exploration(${playerStarted.id},'Staff summary')`);
      assert.equal(await scalar('select quantity as value from character_inventory where character_id=1'), 1);
    }
    await migration('20260929005000_player_exploration_drop_number.sql');
    const withItemNumber = (await start(26)).rows[0];
    assert.equal(withItemNumber.drop_roll == null, withItemNumber.resolution_outcome === 'failure');
    if (withItemNumber.drop_roll != null) assert.ok(withItemNumber.drop_roll >= 1 && withItemNumber.drop_roll <= 100);
    assert.equal((await start(26)).rows[0].drop_roll, withItemNumber.drop_roll);
    await db.query(`select cancel_follower_exploration(${withItemNumber.id},'Cancelled')`);
    const pendingDrop = (await db.query(`insert into follower_explorations
      (character_id,location_id,destination,objective,suitability_percent,request_id,resolution_outcome,roll_origin)
      values(1,${place},'Old success','Explore',0,'00000000-0000-4000-8000-000000000027','success','player') returning id`)).rows[0].id;
    await assert.rejects(db.query(`select resolve_follower_exploration(${pendingDrop},'Too early')`), /item number is required/);
    await migration('20260929006000_backfill_exploration_drop_numbers.sql');
    const itemNumber = await scalar(`select drop_roll as value from follower_explorations where id=${pendingDrop}`);
    assert.ok(itemNumber >= 1 && itemNumber <= 100);
    await migration('20260929006000_backfill_exploration_drop_numbers.sql');
    assert.equal(await scalar(`select drop_roll as value from follower_explorations where id=${pendingDrop}`), itemNumber);
    assert.equal((await db.query('select * from get_player_follower_explorations(1)')).rows[0].drop_roll, itemNumber);
    await db.query(`select resolve_follower_exploration(${pendingDrop},'Staff summary')`);
  } finally { await db.close(); }
});
