create or replace function public.roll_item_acquisition(
  p_request_id bigint
)
returns public.item_acquisition_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  request_row public.item_acquisition_requests;
  item_row public.items;
  rolled_value integer;
  outcome_value text;
  consequence_value text;
begin
  if not public.is_active_staff() then raise exception 'Staff access required'; end if;
  select * into request_row from public.item_acquisition_requests
  where id = p_request_id for update;
  if not found or request_row.status <> 'awaiting_roll' then
    raise exception 'Request is not awaiting a roll';
  end if;
  if request_row.resolution_roll is not null then raise exception 'Request already rolled'; end if;
  select * into item_row from public.items where id = request_row.item_id;

  rolled_value := floor(random() * 100 + 1)::integer;
  outcome_value := case
    when rolled_value <= 5 then 'critical_success'
    when rolled_value <= request_row.success_chance_percent then 'success'
    when rolled_value >= 96 then 'critical_failure'
    else 'failure'
  end;
  consequence_value := case outcome_value
    when 'critical_success' then 'ติดต่อและลักลอบสำเร็จโดยไม่ทิ้งร่องรอย'
    when 'success' then 'ติดต่อและลักลอบสำเร็จ ดำเนินการจัดหาต่อได้'
    when 'critical_failure' then coalesce(
      item_row.critical_failure_consequence,
      'ล้มเหลวร้ายแรงและเกิดเบาะแสให้ฝ่ายตรวจการติดตาม'
    )
    else coalesce(item_row.failure_consequence, 'การจัดหาล้มเหลวและต้องปิดคำร้อง')
  end;

  update public.item_acquisition_requests set
    resolution_roll = rolled_value,
    resolution_outcome = outcome_value,
    consequence = consequence_value,
    status = case when outcome_value in ('success', 'critical_success')
      then 'procuring' else 'risk_review' end,
    reviewed_by = auth.uid(),
    updated_at = now()
  where id = p_request_id
  returning * into request_row;
  return request_row;
end;
