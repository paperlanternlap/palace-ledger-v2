drop function if exists public.get_player_item_catalog(integer);
create function public.get_player_item_catalog(
  p_character_id integer
)
returns table (
  id bigint,
  name text,
  description text,
  cost integer,
  price_currency text,
  acquisition_type text,
  catalog_visibility text,
  acquisition_requires_roll boolean,
  minimum_favor integer,
  fulfillment_days_min integer,
  fulfillment_days_max integer,
  is_limited boolean,
  stock_quantity integer,
  use_category text,
  unlocked boolean,
  can_request boolean,
  action_label text,
  acquisition_channel_name text,
  acquisition_channel_role text,
  acquisition_channel_access_reason text,
  acquisition_channel_motivation text,
  acquisition_unlock_method text,
  acquisition_risk_summary text,
  acquisition_risk_level integer
)
language sql
security definer
set search_path = public
stable
as $$
  with character_row as (
    select
      character.id,
      character.position,
      coalesce(character.favor, 0) as favor,
      coalesce(privilege.can_command_external_purchase, false) as can_command
    from public.characters character
    left join public.character_position_acquisition_privileges privilege
      on privilege.position = character.position
    where character.id = p_character_id
  )
  select
    item.id,
    case when item.catalog_visibility = 'locked' and unlock.id is null
      then 'ช่องทางที่ยังไม่เปิดเผย' else item.name end,
    case when item.catalog_visibility = 'locked' and unlock.id is null
      then 'ต้องค้นหาเบาะแสหรือสร้างความไว้วางใจก่อนจึงจะติดต่อช่องทางนี้ได้'
      else item.description end,
    item.cost,
    item.price_currency,
    item.acquisition_type,
    item.catalog_visibility,
    item.acquisition_requires_roll,
    item.minimum_favor,
    case
      when item.acquisition_type = 'external_legal' and character_row.can_command
        then greatest(0, item.fulfillment_days_min - 1)
      else item.fulfillment_days_min
    end,
    case
      when item.acquisition_type = 'external_legal' and character_row.can_command
        then greatest(
          greatest(0, item.fulfillment_days_min - 1),
          item.fulfillment_days_max - 2
        )
      else item.fulfillment_days_max
    end,
    item.is_limited,
    item.stock_quantity,
    item.use_category,
    unlock.id is not null,
    case
      when item.acquisition_type = 'story_only' then false
      when item.catalog_visibility = 'locked' and unlock.id is null then false
      when character_row.favor < item.minimum_favor then false
      when item.is_limited and item.stock_quantity <= 0 then false
      else true
    end,
    case
      when item.acquisition_type = 'story_only' then 'ได้รับจากการสำรวจเท่านั้น'
      when item.catalog_visibility = 'locked' and unlock.id is null
        then 'ยังไม่ปลดล็อกช่องทาง'
      when character_row.favor < item.minimum_favor
        then 'โปรดปรานยังไม่ถึงเกณฑ์'
      when item.acquisition_type = 'palace_stock' then 'เบิกจากคลัง'
      when item.acquisition_type = 'external_legal' and character_row.can_command
        then 'ออกคำสั่งให้จัดซื้อ'
      when item.acquisition_type = 'external_legal' then 'ส่งคำขอจัดซื้อ'
      when item.acquisition_type = 'restricted' then 'ติดต่อคนกลาง'
      else 'ไม่สามารถขอได้'
    end,
    case when unlock.id is not null then channel.npc_name else null end,
    case when unlock.id is not null then channel.npc_role else null end,
    case when unlock.id is not null then channel.access_reason else null end,
    case when unlock.id is not null then channel.motivation else null end,
    case when unlock.id is not null then channel.unlock_method else null end,
    case when unlock.id is not null then channel.risk_summary else null end,
    item.acquisition_risk_level
  from public.items item
  cross join character_row
  left join public.character_catalog_unlocks unlock
    on unlock.character_id = character_row.id and unlock.item_id = item.id
  left join public.acquisition_channels channel
    on channel.id = item.acquisition_channel_id and channel.active
  where item.active
    and item.catalog_visibility <> 'staff_only'
    and (
      item.shop_available
      or item.acquisition_type = 'story_only'
      or item.catalog_visibility = 'locked'
    )
  order by
    case item.acquisition_type
      when 'palace_stock' then 1
      when 'external_legal' then 2
      when 'restricted' then 3
      else 4
    end,
    item.name;
$$;

create or replace function public.submit_item_acquisition_request(
  p_character_id integer,
  p_item_id bigint,
  p_quantity integer default 1,
  p_player_note text default null
)
returns public.item_acquisition_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  character_row public.characters;
  item_row public.items;
  unlock_row public.character_catalog_unlocks;
  request_row public.item_acquisition_requests;
  route_value text;
  should_auto_fulfill boolean;
  can_command boolean := false;
  total_cost integer;
begin
  if p_quantity <= 0 then raise exception 'Quantity must be positive'; end if;

  select * into character_row from public.characters
  where id = p_character_id for update;
  if not found then raise exception 'Character not found'; end if;

  select * into item_row from public.items
  where id = p_item_id and active for update;
  if not found then raise exception 'Catalog item not found'; end if;

  if item_row.acquisition_type = 'story_only' then
    raise exception 'Story items cannot be requested from the catalog';
  end if;
  if item_row.catalog_visibility = 'staff_only' then
    raise exception 'Catalog item is not available';
  end if;
  if item_row.catalog_visibility = 'locked' then
    select * into unlock_row from public.character_catalog_unlocks
    where character_id = p_character_id and item_id = p_item_id;
    if not found then raise exception 'Acquisition channel is locked'; end if;
  end if;
  if coalesce(character_row.favor, 0) < item_row.minimum_favor then
    raise exception 'Insufficient Favor threshold';
  end if;
  if item_row.price_currency <> 'rp' then
    raise exception 'Catalog acquisition must use RP; Favor is an access threshold';
  end if;

  select exists (
    select 1
    from public.character_position_acquisition_privileges privilege
    where privilege.position = character_row.position
      and privilege.can_command_external_purchase
  ) into can_command;

  total_cost := item_row.cost * p_quantity;
  route_value := case
    when item_row.acquisition_type = 'palace_stock' then 'requisition'
    when item_row.acquisition_type = 'external_legal' and can_command then 'command'
    when item_row.acquisition_type = 'external_legal' then 'procurement'
    else 'restricted_contact'
  end;
  should_auto_fulfill := item_row.acquisition_type = 'palace_stock'
    and item_row.auto_fulfill and not item_row.acquisition_requires_roll;

  if should_auto_fulfill then
    if coalesce(character_row.rp, 0) < total_cost then raise exception 'Insufficient RP'; end if;
    if item_row.is_limited and item_row.stock_quantity < p_quantity then
      raise exception 'Item is out of stock';
    end if;
    update public.characters set rp = coalesce(rp, 0) - total_cost
      where id = p_character_id;
    if item_row.is_limited then
      update public.items set stock_quantity = stock_quantity - p_quantity, updated_at = now()
      where id = p_item_id;
    end if;
    insert into public.character_inventory (character_id, item_name, quantity)
    values (p_character_id, item_row.name, p_quantity)
    on conflict (character_id, item_name)
    do update set quantity = public.character_inventory.quantity + excluded.quantity;
    insert into public.item_acquisition_requests (
      character_id, item_id, quantity, request_route, status, player_note,
      charged_currency, charged_amount, item_granted, requested_by, completed_at,
      acquisition_channel_id
    ) values (
      p_character_id, p_item_id, p_quantity, route_value, 'completed',
      nullif(btrim(p_player_note), ''), 'rp', total_cost, true, auth.uid(), now(),
      item_row.acquisition_channel_id
    ) returning * into request_row;
    insert into public.inventory_transactions (
      item_id, character_id, quantity_change, transaction_type, note
    ) values (
      p_item_id, p_character_id, -p_quantity, 'purchase',
      'เบิกจากคลังผ่านแคตตาล็อก · ' || total_cost || ' RP'
    );
  else
    insert into public.item_acquisition_requests (
      character_id, item_id, quantity, request_route, status, player_note,
      success_chance_percent, requested_by, acquisition_channel_id, roll_phase
    ) values (
      p_character_id, p_item_id, p_quantity, route_value, 'submitted',
      nullif(btrim(p_player_note), ''),
      case when item_row.acquisition_requires_roll
        then item_row.acquisition_success_percent else null end,
      auth.uid(), item_row.acquisition_channel_id,
      case when item_row.acquisition_requires_roll
        then 'contact_and_smuggling' else null end
    ) returning * into request_row;
  end if;

  insert into public.character_history (character_id, action, value, type)
  values (
    p_character_id,
    case when should_auto_fulfill then 'เบิกไอเท็ม' else 'ส่งคำร้องจัดหาไอเท็ม' end,
    item_row.name || ' ×' || p_quantity,
    'item_acquisition'
  );
  return request_row;
end;
$$;

