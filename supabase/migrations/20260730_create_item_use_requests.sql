alter table public.items
  add column if not exists use_category text not null default 'general',
  add column if not exists default_channel text,
  add column if not exists requires_target boolean not null default false,
  add column if not exists requires_roll boolean not null default false,
  add column if not exists action_template jsonb not null default '[]'::jsonb;

create table if not exists public.item_use_requests (
  id bigint generated by default as identity primary key,
  requester_character_id integer not null references public.characters(id) on delete restrict,
  target_character_id integer references public.characters(id) on delete set null,
  item_id bigint not null references public.items(id) on delete restrict,
  quantity integer not null default 1 check (quantity > 0),
  request_type text not null default 'self'
    check (request_type in ('self', 'target', 'secret_plan', 'shared_plot', 'unlock', 'defense')),
  actor_name text,
  use_channel text,
  desired_effect text not null,
  details text,
  role_url text,
  secrecy_level text not null default 'normal'
    check (secrecy_level in ('normal', 'staff_only', 'anonymous')),
  status text not null default 'submitted'
    check (status in (
      'submitted', 'revision', 'approved', 'action_pending',
      'awaiting_player', 'completed', 'rejected', 'cancelled'
    )),
  item_reserved boolean not null default false,
  staff_note text,
  requested_by uuid references auth.users(id) on delete set null,
  reviewed_by uuid references auth.users(id) on delete set null,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.item_request_tasks (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.item_use_requests(id) on delete cascade,
  label text not null,
  task_type text not null default 'staff_action',
  status text not null default 'pending'
    check (status in ('pending', 'done', 'skipped')),
  sort_order integer not null default 0,
  completed_by uuid references auth.users(id) on delete set null,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists item_use_requests_status_submitted
  on public.item_use_requests (status, submitted_at desc);

create index if not exists item_request_tasks_request_sort
  on public.item_request_tasks (request_id, sort_order, id);

alter table public.item_use_requests enable row level security;
alter table public.item_request_tasks enable row level security;

