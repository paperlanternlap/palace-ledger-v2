create table if not exists public.exploration_locations (
  id bigint generated by default as identity primary key,
  code text not null unique,
  zone_number integer not null unique check (zone_number between 1 and 99),
  name text not null,
  short_name text not null,
  category text not null,
  summary text,
  tags text[] not null default '{}',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.exploration_locations enable row level security;

drop policy if exists "Anyone can view active exploration locations"
  on public.exploration_locations;
create policy "Anyone can view active exploration locations"
  on public.exploration_locations for select
  to anon, authenticated
  using (active);

drop policy if exists "Staff can manage exploration locations"
  on public.exploration_locations;
create policy "Staff can manage exploration locations"
  on public.exploration_locations for all
  to authenticated
  using (public.is_active_staff())
  with check (public.is_active_staff());

grant select on public.exploration_locations to anon, authenticated;
grant insert, update, delete on public.exploration_locations to authenticated;
grant usage, select on sequence public.exploration_locations_id_seq
  to authenticated;

