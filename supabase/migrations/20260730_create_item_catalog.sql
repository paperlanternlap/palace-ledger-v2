create or replace function public.adjust_item_stock(
  p_item_id bigint,
  p_quantity_change integer,
  p_note text default null
)
returns public.items
language plpgsql
security definer
set search_path = public
as $$
declare
  target_item public.items;
  next_quantity integer;
begin
  if not public.is_active_staff() then
    raise exception 'Staff access required';
  end if;

  if p_quantity_change = 0 then
    raise exception 'Quantity change must not be zero';
  end if;

  select * into target_item
  from public.items
  where id = p_item_id
  for update;

  if not found then
    raise exception 'Item not found';
  end if;

  if not target_item.is_limited then
    raise exception 'Unlimited items do not use stock quantity';
  end if;

  next_quantity := target_item.stock_quantity + p_quantity_change;
  if next_quantity < 0 then
    raise exception 'Insufficient stock';
  end if;

  update public.items
  set stock_quantity = next_quantity, updated_at = now()
  where id = p_item_id
  returning * into target_item;

  insert into public.inventory_transactions (
    item_id,
    quantity_change,
    transaction_type,
    note,
    created_by
  )
  values (
    p_item_id,
    p_quantity_change,
    case when p_quantity_change > 0 then 'restock' else 'adjustment' end,
    nullif(p_note, ''),
    auth.uid()
  );

  return target_item;
end;
$$;

create or replace function public.grant_catalog_item(
  p_item_id bigint,
  p_character_id integer,
  p_quantity integer,
  p_note text default null
)
returns public.items
language plpgsql
security definer
set search_path = public
as $$
declare
  target_item public.items;
begin
  if not public.is_active_staff() then
    raise exception 'Staff access required';
  end if;

  if p_quantity <= 0 then
    raise exception 'Quantity must be greater than zero';
  end if;

  select * into target_item
  from public.items
  where id = p_item_id and active
  for update;

  if not found then
    raise exception 'Active item not found';
  end if;

  if target_item.is_limited then
    if target_item.stock_quantity < p_quantity then
      raise exception 'Insufficient stock';
    end if;

    update public.items
    set stock_quantity = stock_quantity - p_quantity, updated_at = now()
    where id = p_item_id
    returning * into target_item;
  end if;

  insert into public.character_inventory (character_id, item_name, quantity)
  values (p_character_id, target_item.name, p_quantity)
  on conflict (character_id, item_name)
  do update set quantity = public.character_inventory.quantity + excluded.quantity;

  insert into public.inventory_transactions (
    item_id,
    character_id,
    quantity_change,
    transaction_type,
    note,
    created_by
  )
  values (
    p_item_id,
    p_character_id,
    -p_quantity,
    'grant',
    nullif(p_note, ''),
    auth.uid()
  );

  return target_item;
end;
$$;

revoke all on function public.adjust_item_stock(bigint, integer, text) from public;
revoke all on function public.grant_catalog_item(bigint, integer, integer, text) from public;
grant execute on function public.adjust_item_stock(bigint, integer, text) to authenticated;
grant execute on function public.grant_catalog_item(bigint, integer, integer, text) to authenticated;
