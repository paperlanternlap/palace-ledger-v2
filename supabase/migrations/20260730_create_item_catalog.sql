create unique index if not exists character_inventory_character_item
  on public.character_inventory (character_id, item_name);

create table if not exists public.items (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  is_limited boolean not null default false,
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  low_stock_threshold integer not null default 5 check (low_stock_threshold >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_transactions (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items(id) on delete restrict,
  character_id integer references public.characters(id) on delete set null,
  quantity_change integer not null,
  transaction_type text not null
    check (transaction_type in ('initial', 'restock', 'adjustment', 'grant', 'revoke', 'use')),
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists inventory_transactions_item_created_at
  on public.inventory_transactions (item_id, created_at desc);

insert into public.items (name, is_limited, stock_quantity)
select distinct trim(item_name), false, 0
from public.character_inventory
where nullif(trim(item_name), '') is not null
on conflict (name) do nothing;

alter table public.items enable row level security;
alter table public.inventory_transactions enable row level security;

create policy "Staff can view item catalog"
  on public.items for select
  to authenticated
  using (public.is_active_staff());

create policy "Staff can create catalog items"
  on public.items for insert
  to authenticated
  with check (public.is_active_staff());

create policy "Staff can update item metadata"
  on public.items for update
  to authenticated
  using (public.is_active_staff())
  with check (public.is_active_staff());

create policy "Staff can view inventory transactions"
